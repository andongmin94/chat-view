class Fixture:
    def __init__(self, trial: bool = False) -> None:
        self.process = subprocess.Popen(
            ["node", "--experimental-strip-types", "tools/management-browser-fixture.mts"] +
            (["--trial-preview"] if trial else []),
            cwd=ROOT, stdin=subprocess.PIPE, stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL, text=True, encoding="utf-8",
        )
        self.lines: queue.Queue[str] = queue.Queue()
        def read() -> None:
            assert self.process.stdout
            for line in self.process.stdout:
                self.lines.put(line)
            self.lines.put("")
        threading.Thread(target=read, daemon=True).start()
        data = self.receive()
        assert data.get("ready") is True, "fixture ready"
        self.origin: str = data["origin"]
        assert self.origin.startswith("http://127.0.0.1:"), "private fixture origin"

    def receive(self) -> dict:
        data = json.loads(self.lines.get(timeout=10))
        assert "error" not in data, "server fixture invariants"
        return data

    def command(self, op: str) -> dict:
        assert self.process.stdin
        self.process.stdin.write(json.dumps({"op": op}) + "\n")
        self.process.stdin.flush()
        try:
            return self.receive()
        except AssertionError:
            # A fixed parent opcode is not private provider/browser data.
            # The child deliberately scrubs exception bodies and capabilities.
            raise AssertionError(f"server fixture invariant during {op}") from None

    def close(self) -> None:
        if self.process.poll() is None:
            try:
                self.command("close")
                self.process.wait(timeout=5)
            except Exception:
                self.process.kill()
                self.process.wait(timeout=5)


class Flow:
    def __init__(self, browser: Browser, fixture: Fixture, width: int = 1000):
        self.f = fixture
        self.context = browser.new_context(viewport={"width": width, "height": 900})
        self.context.set_default_timeout(5000)
        self.page = self.context.new_page()
        self.page.set_default_navigation_timeout(10000)
        # Playwright route() only intercepts the first URL of a redirect chain.
        # Use its documented CDPSession for this narrow provider stub instead:
        # Fetch.requestPaused also exposes redirected requests. Service requests
        # continue unchanged; browser cookies/Origin/CSP are never overridden.
        self.network = self.context.new_cdp_session(self.page)
        self.network.on("Fetch.requestPaused", self.route)
        self.network.send("Fetch.enable", {"patterns": [{"urlPattern": "*", "requestStage": "Request"}]})

    def route(self, event: dict) -> None:
        request = event["request"]
        request_id = event["requestId"]
        url = urlsplit(request["url"])
        if request["url"].startswith(self.f.origin + "/"):
            self.network.send("Fetch.continueRequest", {"requestId": request_id})
            return
        if url.scheme == "https" and url.netloc == "chzzk.naver.com":
            headers = {key.lower(): value for key, value in request["headers"].items()}
            assert not headers.get("referer"), "service never sends an external Referer"
            assert not headers.get("authorization"), "provider page receives no native credential"
            state = parse_qs(url.query).get("state", [""])[0]
            assert len(state) == 64, "provider state generated by service"
            links = []
            for owner in ("alice", "bob", "charlie"):
                callback = self.f.origin + "/callback?" + urlencode({"state": state, "code": owner})
                links.append(f'<a id="{owner}" href="{html.escape(callback, quote=True)}">{owner}</a>')
            cancel = self.f.origin + "/callback?" + urlencode({"state": state, "error": "fixture-denied"})
            links += [f'<a id="cancel" href="{html.escape(cancel, quote=True)}">cancel</a>',
                      f'<a id="unrelated" href="{self.f.origin}/campaigns">unrelated</a>']
            body = ('<h1>Synthetic provider</h1>' + "<p>".join(links)).encode("utf-8")
            self.network.send("Fetch.fulfillRequest", {"requestId": request_id, "responseCode": 200,
                "responseHeaders": [{"name": "Content-Type", "value": "text/html; charset=utf-8"}],
                "body": base64.b64encode(body).decode("ascii")})
            return
        self.network.send("Fetch.failRequest", {"requestId": request_id, "errorReason": "BlockedByClient"})

    def cookie(self) -> str:
        cookies = [c for c in self.context.cookies() if c["name"] == "__Host-chatview"]
        assert len(cookies) == 1, "browser accepted exactly one host cookie"
        cookie = cookies[0]
        assert cookie["secure"] and cookie["httpOnly"], "secure HttpOnly cookie"
        assert cookie["sameSite"] == "Lax" and cookie["path"] == "/", "cookie scope"
        assert cookie["domain"] == "127.0.0.1", "host-only cookie"
        assert "__Host-chatview" not in self.page.evaluate("document.cookie"), "HttpOnly isolation"
        return cookie["value"]

    def start(self, path: str) -> None:
        self.page.goto(self.f.origin + path)
        expect(self.page.locator("h1")).to_have_text("브라우저 관리 로그인")
        self.cookie()
        self.page.get_by_role("button", name="치지직으로 브라우저 로그인", exact=True).click()
        expect(self.page.locator("h1")).to_have_text("Synthetic provider")

    def identity(self, path: str, owner: str = "alice") -> None:
        self.start(path)
        old = self.cookie()
        with self.page.expect_response(lambda r: urlsplit(r.url).path == "/account/confirm") as arrival:
            self.page.locator("#" + owner).click()
        assert arrival.value.status == 200, f"callback landing returned {arrival.value.status}"
        expect(self.page.locator("h1")).to_have_text("관리할 채널 확인")
        expect(self.page.locator("body")).to_contain_text(f"channel <{owner}>")
        assert self.cookie() != old, "callback rotates anonymous identity"

    def confirm(self, path: str, owner: str = "alice") -> None:
        old = self.cookie()
        self.page.get_by_role("button", name="이 채널로 관리 계속", exact=True).click()
        expect(self.page).to_have_url(self.f.origin + path)
        expect(self.page.get_by_role("region", name="브라우저 관리 계정")).to_contain_text(f"channel <{owner}>")
        assert self.cookie() != old, "explicit confirmation rotates identity again"

    def image(self, name: str) -> None:
        assert self.page.evaluate("document.documentElement.scrollWidth <= innerWidth"), "no horizontal overflow"
        self.page.screenshot(path=str(OUT / (name + ".png")), full_page=True)

    def close(self) -> None:
        self.context.close()


